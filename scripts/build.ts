/** Bundles the plugin: plugin-src/main.ts → plugin/code.js, ui-src → plugin/ui.html (inlined script). */
const root = new URL('..', import.meta.url).pathname;

const PLACEHOLDER = '__BUILD_HASH__';

async function bundle(entry: string): Promise<string> {
    const result = await Bun.build({ entrypoints: [`${root}${entry}`], target: 'browser', format: 'iife', minify: false, define: { __BUILD__: JSON.stringify(PLACEHOLDER) } });
    if (!result.success) {
        for (const log of result.logs) console.error(log);
        throw new Error(`Build failed: ${entry}`);
    }
    const out = result.outputs[0];
    if (!out) throw new Error(`No output for ${entry}`);
    return out.text();
}

const main = await bundle('plugin-src/main.ts');
const ui = await bundle('ui-src/ui.ts');
const template = await Bun.file(`${root}ui-src/ui.html`).text();

const hash = new Bun.CryptoHasher('sha256').update(main).update(ui).update(template).digest('hex').slice(0, 8);
const stamp = (code: string) => code.replaceAll(PLACEHOLDER, hash);

await Bun.write(`${root}plugin/code.js`, `// Generated by scripts/build.ts. Edit plugin-src/, then run \`bun run build\`.\n${stamp(main)}`);
await Bun.write(`${root}plugin/ui.html`, template.replace('/*UI_BUNDLE*/', () => stamp(ui).replace(/<\/script/gi, '<\\/script')));
await Bun.write(`${root}plugin/build.json`, `${JSON.stringify({ build: hash })}\n`);

console.log(`Built plugin/code.js and plugin/ui.html (build ${hash})`);
